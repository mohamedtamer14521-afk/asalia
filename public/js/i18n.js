class I18nManager {
  constructor() {
    this.lang = localStorage.getItem('asalia_lang') || 'ar'; // Default to Arabic for Egyptian market, easily switchable
    this.init();
  }

  init() {
    this.applyLanguage(this.lang);
  }

  setLanguage(lang) {
    if (lang !== 'en' && lang !== 'ar') return;
    this.lang = lang;
    localStorage.setItem('asalia_lang', lang);
    this.applyLanguage(lang);
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  applyLanguage(lang) {
    const isRtl = lang === 'ar';
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';

    // Update all text nodes with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach((elem) => {
      const key = elem.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        elem.textContent = translations[lang][key];
      }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach((elem) => {
      const key = elem.getAttribute('data-i18n-placeholder');
      if (translations[lang] && translations[lang][key]) {
        elem.setAttribute('placeholder', translations[lang][key]);
      }
    });

    // Update lang button text
    const langBtn = document.getElementById('lang-toggle-btn');
    if (langBtn) {
      langBtn.textContent = lang === 'ar' ? 'English' : 'العربية';
    }
  }

  t(key, fallback = '') {
    if (translations[this.lang] && translations[this.lang][key]) {
      return translations[this.lang][key];
    }
    if (translations['en'] && translations['en'][key]) {
      return translations['en'][key];
    }
    return fallback || key;
  }
}

const i18n = new I18nManager();
window.i18n = i18n;
